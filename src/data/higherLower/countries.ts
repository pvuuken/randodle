import type { DataSource, HigherLowerItem } from "./types";

/**
 * Production Higher or Lower country dataset — all 195 Randodle countries
 * (ids, names and flags follow src/data/countryList.ts).
 *
 * population: World Bank WDI "Population, total" (SP.POP.TOTL), reference year 2023.
 * area: World Bank WDI "Surface area (sq. km)" (AG.SRF.TOTL.K2) — total area incl. inland water, km², 2023.
 * Exception: the Holy See is not covered by the World Bank; its values come from
 * the CIA World Factbook (population estimate 2024, total area 0.44 km²).
 */
export const WORLD_BANK_SOURCE: DataSource = {
  name: "World Bank, World Development Indicators (SP.POP.TOTL, AG.SRF.TOTL.K2)",
  url: "https://data.worldbank.org/indicator/SP.POP.TOTL",
  referenceDate: "2023",
};

export const VATICAN_SOURCE: DataSource = {
  name: "CIA World Factbook — Holy See (Vatican City)",
  url: "https://www.cia.gov/the-world-factbook/countries/holy-see-vatican-city/",
  referenceDate: "2024",
};

const item = (
  id: string,
  en: string,
  nl: string,
  population: number,
  area: number,
  source: DataSource = WORLD_BANK_SOURCE,
): HigherLowerItem => ({
  id,
  name: { en, nl },
  category: "countries",
  metrics: { population, area },
  source,
  image: { url: `/flags/${id.toLowerCase()}.svg` },
  metadata: { populationYear: source === WORLD_BANK_SOURCE ? 2023 : 2024, areaDefinition: "total" },
});

